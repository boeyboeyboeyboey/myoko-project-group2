// Builds src/lib/journeyMapData.ts from Natural Earth 1:10m admin-1 (public domain).
// Usage: node scripts/build-journey-map.mjs <path/to/ne_10m_admin_1_states_provinces.geojson>
// Source: https://github.com/nvkelso/natural-earth-vector (geojson/ne_10m_admin_1_states_provinces.geojson)
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";

const src = process.argv[2];
if (!src) throw new Error("pass the admin-1 geojson path");
const fc = JSON.parse(readFileSync(src, "utf8"));

const W = 1000, H = 920;
const CENTER = [139.0, 36.15];
const SPAN_DEG = 5.2; // longitude span of the wide view
const k = W / ((SPAN_DEG * Math.PI) / 180);
const proj = geoMercator().center(CENTER).scale(k).translate([W / 2, H / 2]).clipExtent([[-60, -60], [W + 60, H + 60]]);
const path = geoPath(proj).digits(2);

// Myoko close-up window (projected) keeps full detail; elsewhere thin hard.
const [zx0, zy0] = proj([138.0, 37.05]);
const [zx1, zy1] = proj([138.45, 36.7]);
const inZoom = (x, y) => x > zx0 && x < zx1 && y > zy0 && y < zy1;

const wanted = fc.features.filter((f) => f.properties.iso_a2 === "JP");
const out = [];
const bytes = { raw: 0 };
for (const f of wanted) {
  const d = path(f);
  if (!d) continue;
  const rings = d.split("M").filter(Boolean);
  const kept = [];
  for (const r of rings) {
    const pts = r.replace(/Z$/, "").split("L").map((s) => s.split(",").map(Number));
    if (pts.length < 3) continue;
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    const area = (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys));
    if (area < 14) continue; // drop specks
    const thin = [pts[0]];
    for (let i = 1; i < pts.length; i++) {
      const p = pts[i], q = thin[thin.length - 1];
      const step = inZoom(p[0], p[1]) ? 0.35 : 1.1;
      if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= step || i === pts.length - 1) thin.push(p);
    }
    if (thin.length < 3) continue;
    kept.push("M" + thin.map((p) => `${+p[0].toFixed(1)} ${+p[1].toFixed(1)}`).join("L") + "Z");
  }
  if (kept.length) out.push({ name: f.properties.name, d: kept.join("") });
}

// y = ty - k*ln(tan(pi/4 + phi/2)); x = tx + k*lambda
const rad = Math.PI / 180;
const tx = W / 2 - k * CENTER[0] * rad;
const ty = H / 2 + k * Math.log(Math.tan(Math.PI / 4 + (CENTER[1] * rad) / 2));

const body = `// GENERATED by scripts/build-journey-map.mjs — do not edit.
// Source: Natural Earth 1:10m admin-1 (public domain), Japan prefectures, Mercator, simplified.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const MERC = { k: ${k.toFixed(3)}, tx: ${tx.toFixed(3)}, ty: ${ty.toFixed(3)} } as const;
export const PREFECTURES: { name: string; d: string }[] = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../src/lib/journeyMapData.ts", import.meta.url), body);
console.log(out.length, "prefectures,", (body.length / 1024).toFixed(1), "KB");
// sanity: Tokyo Stn must agree with formula
const [px, py] = proj([139.767, 35.681]);
console.log("check", px.toFixed(1), py.toFixed(1), (tx + k * 139.767 * rad).toFixed(1), (ty - k * Math.log(Math.tan(Math.PI / 4 + (35.681 * rad) / 2))).toFixed(1));
